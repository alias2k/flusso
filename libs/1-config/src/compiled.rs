//! Compiling a configuration into a single, portable text artifact.
//!
//! [`compile`] runs the whole load pipeline — read `flusso.toml`, parse every
//! referenced schema, validate and convert into a [`Config`] — and wraps the
//! result in a [`Compiled`] envelope. [`write`](fn@write) serializes that
//! envelope to deterministic TOML; [`load_compiled`] reads it back.
//!
//! The point is deployment: a compiled artifact is one file that carries the
//! full, validated configuration with no scattered YAML and no source tree. It
//! holds no secret it wasn't given literally — `{ env = "VAR" }` references are
//! preserved and resolved where the artifact runs.
//!
//! The artifact is **generated-only, but reviewable**: like `Cargo.lock`, flusso
//! owns and rewrites it, and hand edits are not a supported input — yet it is
//! plain TOML, so a committed lock diffs meaningfully. Output is byte-stable:
//! the same inputs always serialize to the same bytes, and nothing in the
//! envelope changes just because the flusso binary was upgraded.

use std::path::Path;

use serde::{Deserialize, Serialize};

use crate::Config;
use crate::loader::{self, LoadError};

/// The artifact format version, checked on load.
///
/// Compatibility policy for the current major: additive changes to the
/// serialized shape use `#[serde(default)]` (plus `skip_serializing_if` on the
/// write side) and need **no** bump — an older lock keeps loading on a newer
/// binary. A bump marks an incompatible reshape and obliges the bumping release
/// to keep a *reader* for every prior version of the major, so the bump is a
/// migration trigger, never a rejection. Version 1 was the pre-freeze
/// MessagePack format, sanctioned as the last break; it is rejected with a
/// regenerate hint (see [`CompileError::LegacyFormat`]).
pub const FORMAT_VERSION: u8 = 3;

/// The comment header written at the top of every artifact. Static text — part
/// of the byte-stable output, never derived from the producing binary.
const HEADER: &str = "\
# This file is generated by flusso from `flusso.toml` and the schemas it references.\n\
# It is not intended for manual editing.\n";

/// A compiled configuration: the validated [`Config`] plus the format version
/// needed to read it safely.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Compiled {
    /// Artifact format version, checked on load against [`FORMAT_VERSION`].
    pub format_version: u8,
    /// The fully-validated configuration.
    pub config: Config,
}

#[derive(thiserror::Error, Debug)]
pub enum CompileError {
    #[error(transparent)]
    Load(#[from] LoadError),
    #[error("failed to read compiled config `{path}`: {source}")]
    Read {
        path: std::path::PathBuf,
        #[source]
        source: std::io::Error,
    },
    #[error("failed to write compiled config `{path}`: {source}")]
    Write {
        path: std::path::PathBuf,
        #[source]
        source: std::io::Error,
    },
    #[error("failed to encode compiled config: {0}")]
    Encode(#[from] toml::ser::Error),
    #[error("failed to decode compiled config: {0}")]
    Decode(#[from] toml::de::Error),
    #[error(
        "compiled config format version {got} is not supported by this build \
         (expected {expected}); re-run `flusso build` (or `flusso run` without \
         `--locked`) against the `flusso.toml` to regenerate the lock"
    )]
    VersionMismatch { got: u8, expected: u8 },
    #[error(
        "this is not a text lock — it was likely written by an older flusso \
         (the pre-freeze binary format); re-run `flusso build` or `flusso run` \
         with the config to regenerate it"
    )]
    LegacyFormat,
}

/// Compile a `flusso.toml` (and the schemas it references) into a [`Compiled`]
/// envelope. Needs neither a database nor any secret to be set — schemas are
/// self-describing and secrets are deferred.
pub fn compile(config_path: impl AsRef<Path>) -> Result<Compiled, CompileError> {
    let config = loader::load(config_path)?;
    Ok(Compiled {
        format_version: FORMAT_VERSION,
        config,
    })
}

/// Serialize a [`Compiled`] envelope to its TOML bytes. Deterministic: the same
/// envelope always yields the same bytes.
pub fn to_bytes(compiled: &Compiled) -> Result<Vec<u8>, CompileError> {
    let body = toml::to_string(compiled)?;
    Ok(format!("{HEADER}\n{body}").into_bytes())
}

/// Write a [`Compiled`] envelope to `path` as TOML.
pub fn write(compiled: &Compiled, path: impl AsRef<Path>) -> Result<(), CompileError> {
    let path = path.as_ref();
    let bytes = to_bytes(compiled)?;
    write_bytes(&bytes, path)
}

/// Write a [`Compiled`] envelope to `path` unless the file already holds
/// exactly those bytes. Returns whether it wrote — so a no-change rebuild
/// leaves the file (and its mtime) untouched instead of churning a committed
/// lock.
pub fn write_if_changed(compiled: &Compiled, path: impl AsRef<Path>) -> Result<bool, CompileError> {
    write_bytes_if_changed(&to_bytes(compiled)?, path.as_ref())
}

fn write_bytes_if_changed(bytes: &[u8], path: &Path) -> Result<bool, CompileError> {
    if std::fs::read(path).is_ok_and(|existing| existing == bytes) {
        return Ok(false);
    }
    write_bytes(bytes, path)?;
    Ok(true)
}

/// Write `bytes` to the lock at `path`, replacing it whole where the folder
/// allows: written beside the file the path names (through any symlink),
/// with that file's permissions, then renamed over it, so a process stopped
/// mid-write leaves the old lock, never a truncated one. Where no file can be
/// made beside it (a read-only folder) or a rename can't land (a single-file
/// mount, another device), the lock is written in place, as before 0.18.
fn write_bytes(bytes: &[u8], path: &Path) -> Result<(), CompileError> {
    let failed = |source| CompileError::Write {
        path: path.to_path_buf(),
        source,
    };
    let target = std::fs::canonicalize(path).unwrap_or_else(|_| path.to_path_buf());
    match replace(bytes, &target) {
        Ok(()) => Ok(()),
        Err((stage, error)) if falls_back(&error, stage) => {
            tracing::debug!(
                lock = %target.display(),
                %error,
                "can't replace the lock whole here; writing it in place"
            );
            std::fs::write(&target, bytes).map_err(failed)
        }
        Err((_, error)) => Err(failed(error)),
    }
}

/// Which step of [`replace`] failed.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Stage {
    /// Writing the file beside the lock.
    Staging,
    /// Renaming it over the lock.
    Renaming,
}

/// Write `bytes` beside `target` and rename them over it.
fn replace(bytes: &[u8], target: &Path) -> Result<(), (Stage, std::io::Error)> {
    let name = target.file_name().map_or_else(
        || std::ffi::OsString::from("flusso.lock"),
        std::ffi::OsStr::to_os_string,
    );
    let mut temporary_name = std::ffi::OsString::from(".");
    temporary_name.push(&name);
    temporary_name.push(format!(".{}.tmp", std::process::id()));
    let temporary = target.with_file_name(temporary_name);
    let staged = std::fs::File::create(&temporary).and_then(|mut file| {
        if let Ok(existing) = std::fs::metadata(target) {
            file.set_permissions(existing.permissions())?;
        }
        std::io::Write::write_all(&mut file, bytes)?;
        file.sync_all()
    });
    let result = match staged {
        Err(error) => Err((Stage::Staging, error)),
        Ok(()) => std::fs::rename(&temporary, target).map_err(|error| (Stage::Renaming, error)),
    };
    if result.is_err() {
        let _ = std::fs::remove_file(&temporary);
    }
    result
}

/// Whether a failed [`replace`] should fall back to writing the lock in
/// place: no file can be made beside it, or the rename can't cross where the
/// lock sits. Anything else (a full disk, a lock that went away) is reported.
fn falls_back(error: &std::io::Error, stage: Stage) -> bool {
    use std::io::ErrorKind;
    match stage {
        Stage::Staging => matches!(
            error.kind(),
            ErrorKind::PermissionDenied | ErrorKind::ReadOnlyFilesystem
        ),
        Stage::Renaming => matches!(
            error.kind(),
            ErrorKind::ResourceBusy | ErrorKind::CrossesDevices | ErrorKind::PermissionDenied
        ),
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::{Stage, falls_back, write_bytes, write_bytes_if_changed};

    fn scratch(name: &str) -> std::path::PathBuf {
        let dir = std::env::temp_dir().join(format!("flusso-lock-{}-{name}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[cfg(unix)]
    #[test]
    fn a_lock_is_replaced_whole_never_rewritten_in_place() {
        use std::os::unix::fs::MetadataExt;

        let dir = scratch("replace");
        let lock = dir.join("flusso.lock");
        std::fs::write(&lock, b"old").unwrap();
        let before = std::fs::metadata(&lock).unwrap().ino();

        write_bytes(b"new lock", &lock).unwrap();

        assert_eq!(std::fs::read(&lock).unwrap(), b"new lock");
        assert_ne!(
            std::fs::metadata(&lock).unwrap().ino(),
            before,
            "a new file took the old one's name: a stop mid-write leaves the old lock whole"
        );
        let names: Vec<_> = std::fs::read_dir(&dir)
            .unwrap()
            .map(|entry| entry.unwrap().file_name())
            .collect();
        assert_eq!(names, vec![std::ffi::OsString::from("flusso.lock")]);
    }

    #[test]
    fn a_failed_write_leaves_the_old_lock_and_no_stray_file() {
        let dir = scratch("failed");
        let lock = dir.join("flusso.lock");
        std::fs::create_dir_all(lock.join("occupied")).unwrap();

        assert!(write_bytes(b"new lock", &lock).is_err());

        assert!(
            lock.join("occupied").is_dir(),
            "what was there is untouched"
        );
        let names: Vec<_> = std::fs::read_dir(&dir)
            .unwrap()
            .map(|entry| entry.unwrap().file_name())
            .collect();
        assert_eq!(names, vec![std::ffi::OsString::from("flusso.lock")]);
    }

    fn names(dir: &std::path::Path) -> Vec<std::ffi::OsString> {
        let mut names: Vec<_> = std::fs::read_dir(dir)
            .unwrap()
            .map(|entry| entry.unwrap().file_name())
            .collect();
        names.sort();
        names
    }

    #[cfg(unix)]
    #[test]
    fn a_symlinked_lock_updates_its_target_and_stays_a_link() {
        let dir = scratch("symlink");
        std::fs::create_dir_all(dir.join("real")).unwrap();
        std::fs::write(dir.join("real/flusso.lock"), b"old").unwrap();
        let link = dir.join("flusso.lock");
        let _ = std::fs::remove_file(&link);
        std::os::unix::fs::symlink("real/flusso.lock", &link).unwrap();

        write_bytes(b"new lock", &link).unwrap();

        assert!(
            std::fs::symlink_metadata(&link)
                .unwrap()
                .file_type()
                .is_symlink()
        );
        assert_eq!(
            std::fs::read(dir.join("real/flusso.lock")).unwrap(),
            b"new lock"
        );
        assert_eq!(
            names(&dir.join("real")),
            vec![std::ffi::OsString::from("flusso.lock")]
        );
    }

    #[cfg(unix)]
    #[test]
    fn a_lock_in_a_folder_flusso_cannot_write_to_is_written_in_place() {
        use std::os::unix::fs::PermissionsExt;

        let dir = scratch("readonly");
        let lock = dir.join("flusso.lock");
        std::fs::write(&lock, b"old").unwrap();
        std::fs::set_permissions(&dir, std::fs::Permissions::from_mode(0o555)).unwrap();
        let root = std::fs::File::create(dir.join("probe")).is_ok();

        let written = write_bytes(b"new lock", &lock);

        std::fs::set_permissions(&dir, std::fs::Permissions::from_mode(0o755)).unwrap();
        if root {
            return;
        }
        written.unwrap();
        assert_eq!(std::fs::read(&lock).unwrap(), b"new lock");
        assert_eq!(names(&dir), vec![std::ffi::OsString::from("flusso.lock")]);
    }

    #[cfg(unix)]
    #[test]
    fn a_rewritten_lock_keeps_its_permissions() {
        use std::os::unix::fs::PermissionsExt;

        let dir = scratch("permissions");
        let lock = dir.join("flusso.lock");
        std::fs::write(&lock, b"old").unwrap();
        std::fs::set_permissions(&lock, std::fs::Permissions::from_mode(0o640)).unwrap();

        write_bytes(b"new lock", &lock).unwrap();

        let mode = std::fs::metadata(&lock).unwrap().permissions().mode() & 0o777;
        assert_eq!(mode, 0o640);
    }

    #[test]
    fn a_temporary_file_a_crash_left_is_reused_and_not_left_behind() {
        let dir = scratch("leftover");
        let lock = dir.join("flusso.lock");
        std::fs::write(&lock, b"old").unwrap();
        let leftover = dir.join(format!(".flusso.lock.{}.tmp", std::process::id()));
        std::fs::write(
            &leftover,
            b"half a lock from a killed run, longer than the new one",
        )
        .unwrap();

        write_bytes(b"new lock", &lock).unwrap();

        assert_eq!(std::fs::read(&lock).unwrap(), b"new lock");
        assert_eq!(names(&dir), vec![std::ffi::OsString::from("flusso.lock")]);
    }

    #[cfg(unix)]
    #[test]
    fn an_unchanged_lock_is_not_rewritten_or_staged() {
        use std::os::unix::fs::{MetadataExt, PermissionsExt};

        let dir = scratch("unchanged");
        let lock = dir.join("flusso.lock");
        std::fs::write(&lock, b"same").unwrap();
        let before = std::fs::metadata(&lock).unwrap().ino();
        std::fs::set_permissions(&dir, std::fs::Permissions::from_mode(0o555)).unwrap();

        let wrote = write_bytes_if_changed(b"same", &lock);

        std::fs::set_permissions(&dir, std::fs::Permissions::from_mode(0o755)).unwrap();
        assert!(!wrote.unwrap(), "the same bytes are not written");
        assert_eq!(std::fs::metadata(&lock).unwrap().ino(), before);
        assert_eq!(names(&dir), vec![std::ffi::OsString::from("flusso.lock")]);
    }

    #[test]
    fn only_a_place_that_takes_no_rename_falls_back_to_writing_in_place() {
        use std::io::{Error, ErrorKind};

        assert!(falls_back(
            &Error::from(ErrorKind::PermissionDenied),
            Stage::Staging
        ));
        assert!(falls_back(
            &Error::from(ErrorKind::ReadOnlyFilesystem),
            Stage::Staging
        ));
        assert!(falls_back(
            &Error::from(ErrorKind::ResourceBusy),
            Stage::Renaming
        ));
        assert!(falls_back(
            &Error::from(ErrorKind::CrossesDevices),
            Stage::Renaming
        ));
        assert!(!falls_back(
            &Error::from(ErrorKind::StorageFull),
            Stage::Staging
        ));
        assert!(!falls_back(
            &Error::from(ErrorKind::NotFound),
            Stage::Renaming
        ));
    }
}

/// Decode a [`Compiled`] envelope from its TOML bytes, checking the format
/// version. A non-UTF-8 input is diagnosed as the pre-freeze binary format
/// with a regenerate hint.
pub fn from_bytes(bytes: &[u8]) -> Result<Config, CompileError> {
    let text = std::str::from_utf8(bytes).map_err(|_| CompileError::LegacyFormat)?;
    // The version is checked before the body is decoded, so a lock written in
    // another format reports the version mismatch (and its regenerate hint)
    // rather than whichever field of the old shape fails first.
    let header: Header = toml::from_str(text)?;
    if header.format_version != FORMAT_VERSION {
        return Err(CompileError::VersionMismatch {
            got: header.format_version,
            expected: FORMAT_VERSION,
        });
    }
    let compiled: Compiled = toml::from_str(text)?;
    Ok(compiled.config)
}

/// Just the version line of a lock, read ahead of the body.
#[derive(Deserialize)]
struct Header {
    format_version: u8,
}

/// Read a compiled artifact from `path` and return its [`Config`].
pub fn load_compiled(path: impl AsRef<Path>) -> Result<Config, CompileError> {
    let path = path.as_ref();
    let bytes = std::fs::read(path).map_err(|source| CompileError::Read {
        path: path.to_path_buf(),
        source,
    })?;
    from_bytes(&bytes)
}
